export async function generateUniqueCommunityNickname(client: PoolClient) {
  for (let attempt = 0; attempt < 100; attempt += 1) {
    const nickname = createCommunityNicknameCandidate();
    const exists = await client.query<{ exists: boolean }>(
      `
        SELECT EXISTS (
          SELECT 1
          FROM public.users
          WHERE community_nickname = $1
        ) AS exists
      `,
      [nickname],
    );

    if (!exists.rows[0]?.exists) {
      return nickname;
    }
  }

  throw new Error("커뮤니티 닉네임을 생성하지 못했습니다.");
}

function createCommunityNicknameCandidate() {
  for (let attempt = 0; attempt < 100; attempt += 1) {
    const candidate =
      `${pickRandom(ADJECTIVES)}${pickRandom(COLORS)}${pickRandom(ANIMALS)}`;
    if (Array.from(candidate).length <= MAX_COMMUNITY_NICKNAME_LENGTH) {
      return candidate;
    }
  }

  return "귀여운파랑여우";
}

function pickRandom<T>(items: readonly T[]) {
  return items[randomInt(items.length)];
}
