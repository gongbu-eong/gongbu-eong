export function MyPolicyDocumentPage({ documentKey }: { documentKey: PolicyDocumentKey }) {
  const document = policyDocuments[documentKey];

  return (
    <div className={styles.page}>
      <AppHeader />
      <main className={`${styles.frame} ${styles.documentFrame}`}>
        <h1 className={styles.title}>{document.title}</h1>
        <div className={styles.documentBody}>
          {document.sections.map((section, sectionIndex) => (
            <section key={`${section.title}-${sectionIndex}`} className={styles.documentSection}>
              {section.title ? <h2>{section.title}</h2> : null}
              {section.blocks.map((block, blockIndex) => renderBlock(block, `${section.title}-${blockIndex}`))}
            </section>
          ))}
        </div>
        <BusinessInfo className={styles.policyBusinessInfo} />
      </main>
      <AppFooter active="my" />
    </div>
  );
}

function renderBlock(block: PolicyTextBlock | PolicyTable, key: string) {
  if (block.kind === "paragraph" || block.kind === "final") {
    return (
      <p key={key} className={block.kind === "final" ? styles.finalText : undefined}>
        {block.text}
      </p>
    );
  }

  if (block.kind === "ordered") {
    return (
      <ol key={key} start={block.start} className={styles.documentList}>
        {block.items?.map((item, index) => <li key={`${key}-${index}`}>{item}</li>)}
      </ol>
    );
  }

  if (block.kind === "unordered") {
    return (
      <ul key={key} className={styles.documentList}>
        {block.items?.map((item, index) => <li key={`${key}-${index}`}>{item}</li>)}
      </ul>
    );
  }

  if (block.kind === "table") {
    return (
      <table
        key={key}
        className={`${styles.policyTable} ${block.narrowFirstColumn ? styles.policyTableNarrow : ""} ${
          block.dangerFirstColumn ? styles.policyTableDanger : ""
        }`}
      >
        <thead>
          <tr>
            {block.headers.map((header) => (
              <th key={header}>{header}</th>
            ))}
          </tr>
        </thead>
        <tbody>
          {block.rows.map((row, rowIndex) => (
            <tr key={`${key}-${rowIndex}`}>
              {row.map((cell, cellIndex) => (
                <td key={`${key}-${rowIndex}-${cellIndex}`}>{cell}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    );
  }

  return null;
}
